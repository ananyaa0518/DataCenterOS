
#include <iostream>
#include <vector>

#include "disk/DiskRequest.h"
#include "disk/DiskScheduler.h"
#include "process/ContextSwitch.h"

using namespace std;
using namespace datacenteros;

int main() {

    cout << "\n";
    cout << "============================================\n";
    cout << "          SMART STORAGE OS SIMULATOR        \n";
    cout << "============================================\n";

    // ==========================================
    // PART 1: DISK SCHEDULING
    // ==========================================

    cout << "\n========== DISK SCHEDULING ==========\n";

    // Disk contains tracks from 0 to 199.
    DiskScheduler scheduler(0, 199);

    // Sample disk requests generated by processes.
    vector<DiskRequest> requests = {
        {1, 98, 101},
        {2, 183, 102},
        {3, 37, 103},
        {4, 122, 101},
        {5, 14, 102},
        {6, 65, 103}
    };

    int initialHead = 53;

    cout << "\nInitial Disk Head Position: "
         << initialHead << "\n";

    cout << "Total Disk Requests: "
         << requests.size() << "\n";

    // Algorithms to compare.
    vector<DiskAlgorithm> algorithms = {
        DiskAlgorithm::FCFS,
        DiskAlgorithm::SSTF,
        DiskAlgorithm::SCAN,
        DiskAlgorithm::CSCAN,
        DiskAlgorithm::LOOK
    };

    // Run every algorithm.
    for (DiskAlgorithm algorithm : algorithms) {

        DiskScheduleResult result =
            scheduler.schedule(
                requests,
                initialHead,
                algorithm,
                Direction::RIGHT
            );

        cout << "\n--------------------------------------------\n";

        cout << "Algorithm: "
             << DiskScheduler::getAlgorithmName(algorithm)
             << "\n";

        // Display service order.
        cout << "Service Order: ";

        for (const auto& request : result.serviceOrder) {
            cout << request.track << " ";
        }

        cout << "\n";

        // Display head movement path.
        cout << "Disk Head Path: ";

        for (size_t i = 0; i < result.headPath.size(); i++) {

            if (i > 0) {
                cout << " -> ";
            }

            cout << result.headPath[i];
        }

        cout << "\n";

        // Performance metrics.
        cout << "Total Head Movement: "
             << result.totalHeadMovement
             << " tracks\n";

        cout << "Average Seek Distance: "
             << result.averageSeekDistance
             << " tracks\n";

        cout << "Average Waiting Time: "
             << result.averageWaitingTime
             << " movement units\n";

        cout << "--------------------------------------------\n";
    }


    // ==========================================
    // PART 2: CONTEXT SWITCHING
    // ==========================================

    cout << "\n========== CONTEXT SWITCHING ==========\n";

    // Context switcher with 5 cycles overhead.
    ContextSwitcher contextSwitcher(5);

    CPUContext cpu;

    // ------------------------------------------
    // Process 101 starts execution.
    // ------------------------------------------

    cout << "\n[PROCESS 101] Starting execution\n";

    contextSwitcher.dispatchFirst(101, cpu);

    cpu.programCounter = 100;
    cpu.registers[0] = 50;
    cpu.registers[1] = 75;

    cout << "PID: 101\n";
    cout << "Program Counter: "
         << cpu.programCounter << "\n";

    cout << "Register R0: "
         << cpu.registers[0] << "\n";


    // ------------------------------------------
    // Switch from Process 101 to Process 102.
    // ------------------------------------------

    cout << "\n[CONTEXT SWITCH]\n";

    cout << "Saving Process 101 context...\n";

    contextSwitcher.switchTo(102, cpu);

    cout << "Restoring Process 102 context...\n";

    cpu.programCounter = 200;
    cpu.registers[0] = 80;

    cout << "Process 102 is now running.\n";


    // ------------------------------------------
    // Switch back to Process 101.
    // ------------------------------------------

    cout << "\n[CONTEXT SWITCH]\n";

    cout << "Saving Process 102 context...\n";

    contextSwitcher.switchTo(101, cpu);

    cout << "Restoring Process 101 context...\n";

    cout << "\nRestored Process Information:\n";

    cout << "Current PID: "
         << contextSwitcher.getCurrentProcess()
         << "\n";

    cout << "Program Counter: "
         << cpu.programCounter
         << "\n";

    cout << "Register R0: "
         << cpu.registers[0]
         << "\n";

    cout << "Register R1: "
         << cpu.registers[1]
         << "\n";


    // ==========================================
    // PART 3: CONTEXT SWITCH STATISTICS
    // ==========================================

    cout << "\n========== CONTEXT SWITCH STATISTICS ==========\n";

    ContextSwitchStats stats =
        contextSwitcher.getStats();

    cout << "Total Context Switches: "
         << stats.switchCount
         << "\n";

    cout << "Overhead Per Switch: 5 cycles\n";

    cout << "Total Switching Overhead: "
         << stats.overheadCycles
         << " cycles\n";


    // ==========================================
    // SIMULATION COMPLETE
    // ==========================================

    cout << "\n============================================\n";
    cout << "           SIMULATION COMPLETED             \n";
    cout << "============================================\n";

    return 0;
}
